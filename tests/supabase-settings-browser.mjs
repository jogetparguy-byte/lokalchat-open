import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const browser = await chromium.launch({headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? {executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE} : {})});
const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const url = process.env.SETTINGS_HARNESS_URL || 'http://127.0.0.1:5175/settings.html';
const section = page.locator('#supabase');
const finish = fail => page.evaluate(value => window.supabaseHarness.finish(value), fail);
try {
  await page.goto(`${url}?role=sme#configuration`);
  const save = section.getByRole('button', {name: 'Simpan konfigurasi Supabase', exact: true});
  await save.waitFor();
  for (const id of ['supabase-public-key', 'supabase-secret-key']) assert.equal(await page.locator(`#${id}`).getAttribute('type'), 'password');
  await page.locator('#supabase-url').fill('https://chosen.supabase.co');
  await page.locator('#supabase-public-key').fill('sb_publishable_browser_fixture');
  await page.locator('#supabase-secret-key').fill('sb_secret_browser_fixture');
  await section.getByRole('button', {name: 'Paparkan secret key', exact: true}).click();
  assert.equal(await page.locator('#supabase-secret-key').getAttribute('type'), 'text');
  await save.click();
  await section.getByRole('button', {name: 'Menyimpan…', exact: true}).waitFor();
  assert.equal(await page.locator('#supabase-url').isDisabled(), true);
  await finish(false);
  await section.getByRole('status').filter({hasText: 'Profil Supabase disimpan'}).waitFor();
  assert.equal(await page.locator('#supabase-secret-key').inputValue(), '');
  assert.equal(await page.locator('#supabase-secret-key').getAttribute('type'), 'password');
  assert.equal(await page.locator('#supabase-public-key').inputValue(), '');
  await page.waitForFunction(() => window.settingsQueryClient.getMutationCache().getAll().length === 0);
  assert.equal((await page.textContent('body')).includes('sb_secret_browser_fixture'), false);
  await save.click();
  await section.getByRole('button', {name: 'Menyimpan…', exact: true}).waitFor();
  assert.equal(await page.evaluate(() => window.supabaseHarness.calls.at(-1).secretKey), '');
  await finish(false);
  await section.getByRole('status').filter({hasText: 'Profil Supabase disimpan'}).waitFor();
  await page.locator('#supabase-url').fill('https://another.supabase.co');
  assert.equal(await page.locator('#supabase-secret-key').getAttribute('required'), '');
  await page.locator('#supabase-public-key').fill('sb_secret_wrong_scope');
  await page.locator('#supabase-secret-key').fill('sb_secret_another_fixture');
  const previousCalls = await page.evaluate(() => window.supabaseHarness.calls.length);
  await save.click();
  await section.getByRole('alert').filter({hasText: 'Publishable key mesti'}).waitFor();
  assert.equal(await page.evaluate(() => window.supabaseHarness.calls.length), previousCalls);
  await page.locator('#supabase-public-key').fill('sb_publishable_another_fixture');
  await save.click();
  await section.getByRole('button', {name: 'Menyimpan…', exact: true}).waitFor();
  await finish(true);
  await section.getByRole('alert').filter({hasText: 'Konfigurasi gagal disimpan'}).waitFor();
  assert.equal(await page.locator('#supabase-secret-key').inputValue(), 'sb_secret_another_fixture');
  await mkdir('reports/supabase-settings', {recursive: true});
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({width, height: 1000});
    await section.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: `reports/supabase-settings/settings-${width}.png`, fullPage: true});
  }
  await page.goto(`${url}?role=sme#configuration`);
  await save.waitFor();
  assert.equal(await page.locator('#supabase-secret-key').isEnabled(), true);
  assert.equal(await save.isEnabled(), true);
  await page.goto(`${url}?readError=1#configuration`);
  await section.getByRole('alert').filter({hasText: 'Konfigurasi Supabase tidak dapat dimuatkan'}).waitFor();
  assert.equal(await page.locator('#supabase-secret-key').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS Supabase Settings: save/pending/clear keys/cache, retain key, new project, wrong key scope, error, role and responsive widths');
} finally {await browser.close();}
