import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{})});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto(process.env.APP_URL??'http://127.0.0.1:3000/auth');
 await page.getByRole('tab',{name:'Log Masuk',exact:true}).waitFor();
 await page.getByRole('alert').filter({hasText:'Sambungan belum dikonfigurasi'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Log Masuk',exact:true}).isDisabled(),true);
 console.log('PASS production auth: missing config cannot sign in');
 await page.goto('http://127.0.0.1:3000/dashboard/inbox');
 await page.waitForURL('**/auth');
 console.log('PASS production protected route redirects without credentials');
 await page.goto('http://127.0.0.1:5175');
 const input=page.getByRole('textbox',{name:'Balasan pelanggan'});
 await input.fill('Hello customer');
 await page.getByRole('button',{name:'Hantar',exact:true}).click();
 await page.getByRole('button',{name:'Cuba Semula',exact:true}).waitFor();
 assert.equal(await input.inputValue(),'');
 assert.equal(JSON.parse(await page.getByTestId('calls').textContent()).length,1);
 await page.getByRole('button',{name:'Cuba Semula',exact:true}).click();
 await page.getByText('Diterima Meta',{exact:true}).waitFor();
 assert.equal(await page.getByText('Hello customer',{exact:true}).count(),1);
 assert.equal(await page.getByRole('button',{name:'Cuba Semula',exact:true}).count(),0);
 console.log('PASS persisted send failure clears draft; retry updates same bubble');
 await page.getByLabel('Outcome').selectOption('unknown');
 await input.fill('Unknown delivery');
 await page.getByRole('button',{name:'Hantar',exact:true}).click();
 await page.getByRole('button',{name:'Semak & cuba semula',exact:true}).waitFor();
 assert.equal(await input.inputValue(),'Unknown delivery');
 await page.getByRole('button',{name:'Semak & cuba semula',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(document.querySelector('[data-testid="calls"]').textContent).length===3);
 const calls=JSON.parse(await page.getByTestId('calls').textContent());assert.equal(calls[1],calls[2]);
 console.log('PASS uncertain response retains draft and reuses request ID');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS mobile width and no browser runtime errors');
} finally {await browser.close()}
