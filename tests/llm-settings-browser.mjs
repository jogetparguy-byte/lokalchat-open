import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
const page = await browser.newPage({ viewport: {width: 1440, height: 1000} });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const url = process.env.SETTINGS_HARNESS_URL || 'http://127.0.0.1:5175/settings.html';
const finish = fail => page.evaluate(value => window.settingsHarness.finish(value), fail);
try {
  await page.goto(`${url}#configuration`);
  await page.getByRole('heading', { name: 'Provider AI' }).waitFor();
  const save = page.getByRole('button', { name: 'Simpan konfigurasi AI' });
  await save.waitFor();
  assert.equal(await page.locator('#llm-key').getAttribute('type'), 'password');
  await page.getByLabel('ID model', {exact: true}).fill('test-chat-model');
  await page.getByLabel('API key', {exact: true}).fill('sk-browser-fixture-only');
  await page.getByRole('button', {name: 'Papar', exact: true}).click();
  assert.equal(await page.locator('#llm-key').getAttribute('type'), 'text');
  await page.getByRole('button', {name: 'Sembunyi', exact: true}).click();
  assert.equal(await page.locator('#llm-key').getAttribute('type'), 'password');
  await save.click();
  await page.getByRole('button', {name: 'Menyimpan…', exact: true}).waitFor();
  assert.equal(await page.locator('#llm-provider').isDisabled(), true);
  await finish(false);
  await page.getByRole('status').filter({hasText: 'Konfigurasi AI disimpan'}).waitFor();
  assert.equal(await page.locator('#llm-key').inputValue(), '');
  assert.equal(await page.locator('#llm-key').getAttribute('required'), null);
  await page.waitForFunction(() => window.settingsQueryClient.getMutationCache().getAll().length === 0);
  assert.equal((await page.textContent('body')).includes('sk-browser-fixture-only'), false);
  await page.getByLabel('ID model', {exact: true}).fill('changed-model');
  await save.click();
  await page.getByRole('button', {name: 'Menyimpan…', exact: true}).waitFor();
  assert.equal(await page.evaluate(() => window.settingsHarness.calls.at(-1).apiKey), '');
  await finish(false);
  await page.getByRole('status').filter({hasText: 'Konfigurasi AI disimpan'}).waitFor();
  await page.getByLabel('Provider LLM').selectOption('custom');
  assert.equal(await page.locator('#llm-key').getAttribute('required'), '');
  await page.getByLabel('Base URL', {exact: true}).fill('https://api.provider.example/v1');
  await page.getByLabel('ID model', {exact: true}).fill('custom-chat-model');
  await page.locator('#llm-key').fill('sk-new-provider-fixture');
  await save.click();
  await page.getByRole('button', {name: 'Menyimpan…', exact: true}).waitFor();
  await finish(true);
  await page.getByRole('alert').filter({hasText: 'Konfigurasi gagal disimpan'}).waitFor();
  assert.equal(await page.locator('#llm-key').inputValue(), 'sk-new-provider-fixture');
  await mkdir('reports/llm-settings', {recursive: true});
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({width, height: 1000});
    await page.locator('#llm').scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: `reports/llm-settings/settings-${width}.png`, fullPage: true});
  }
  console.log('PASS Settings form: save/loading/success, secret cleared and cache removed, retained key, provider change, error and responsive widths');
  await page.goto(`${url}?role=sme#configuration`);
  await page.getByRole('button', {name: 'Simpan konfigurasi AI'}).waitFor();
  assert.equal(await page.locator('#llm-key').isEnabled(), true);
  await page.getByLabel('ID model', {exact: true}).fill('user-chat-model');
  await page.getByLabel('API key', {exact: true}).fill('sk-ordinary-user-fixture');
  await page.getByRole('button', {name: 'Simpan konfigurasi AI'}).click();
  await page.getByRole('button', {name: 'Menyimpan…', exact: true}).waitFor();
  await finish(false);
  await page.getByRole('status').filter({hasText: 'Konfigurasi AI disimpan'}).waitFor();
  assert.equal(await page.locator('#llm-key').inputValue(), '');
  await page.goto(`${url}?readError=1#configuration`);
  await page.getByRole('alert').filter({hasText: 'Konfigurasi AI tidak dapat dimuatkan'}).waitFor();
  assert.equal(await page.locator('#llm-key').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS Settings form: non-admin access and read-error states; no browser runtime errors');
} finally { await browser.close(); }
